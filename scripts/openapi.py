"""Keeps the SDK's copy of the Flashpi API contract and the types generated from it in sync.

    uv run python scripts/openapi.py sync      download the public OpenAPI document, then generate
    uv run python scripts/openapi.py generate  regenerate src/flashpi/types/_generated.py
    uv run python scripts/openapi.py check     fail when the generated file is out of date (CI)

The source is the public document the docs publish (https://flashpi.com.ec/docs/openapi.json),
because the API repository is private. Override it with FLASHPI_OPENAPI_URL, or point
FLASHPI_OPENAPI_FILE at a local file (for example a flashpi-api checkout).

The generator uses the standard library only. It turns every component schema into a TypedDict
(keys stay as on the wire, in camelCase) or a type alias, and every list operation's query into a
TypedDict. It fails on any construct it does not know, so a change in the document can never be
translated silently into a wrong type.
"""

from __future__ import annotations

import json
import keyword
import os
import sys
import textwrap
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import TypeAlias, cast

ROOT = Path(__file__).resolve().parent.parent
CONTRACT_PATH = ROOT / "openapi" / "openapi.json"
TYPES_PATH = ROOT / "src" / "flashpi" / "types" / "_generated.py"
DEFAULT_URL = "https://flashpi.com.ec/docs/openapi.json"

LINE_LENGTH = 100
INDENT = "    "

Json: TypeAlias = "dict[str, Json] | list[Json] | str | int | float | bool | None"
Schema: TypeAlias = "dict[str, Json]"

HEADER = '''\
"""Types of the Flashpi API, generated from its public OpenAPI document.

GENERATED by scripts/openapi.py from openapi/openapi.json. Do not edit by hand: run
`uv run python scripts/openapi.py sync` (or `generate`).
"""
'''

# Keywords that only constrain values (lengths, patterns, ranges) or document them: a TypedDict
# cannot express them, so they are read for the docstrings or skipped.
ANNOTATION_KEYWORDS = frozenset(
    {
        "description",
        "example",
        "examples",
        "format",
        "pattern",
        "minLength",
        "maxLength",
        "minimum",
        "maximum",
        "exclusiveMinimum",
        "exclusiveMaximum",
        "multipleOf",
        "minItems",
        "maxItems",
        "uniqueItems",
        "minProperties",
        "maxProperties",
        "default",
        "title",
        "deprecated",
    }
)
STRUCTURE_KEYWORDS = frozenset(
    {
        "type",
        "properties",
        "required",
        "items",
        "enum",
        "const",
        "$ref",
        "allOf",
        "anyOf",
        "oneOf",
        "discriminator",
        "additionalProperties",
        "not",
    }
)
SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}


class GenerationError(Exception):
    """The document holds something this generator cannot translate faithfully."""


@dataclass
class Field:
    name: str
    annotation: str
    required: bool
    doc: str


@dataclass
class Definition:
    """A TypedDict (when `fields` is not None) or a type alias (`expression`)."""

    name: str
    doc: str
    fields: list[Field] | None = None
    expression: str = ""
    dependencies: set[str] = field(default_factory=set[str])


def upper_first(value: str) -> str:
    return value[:1].upper() + value[1:]


def as_schema(value: Json, where: str) -> Schema:
    if not isinstance(value, dict):
        raise GenerationError(f"{where}: expected a schema object")
    return value


def as_list(value: Json, where: str) -> list[Json]:
    if not isinstance(value, list):
        raise GenerationError(f"{where}: expected a list")
    return value


def as_str(value: Json, where: str) -> str:
    if not isinstance(value, str):
        raise GenerationError(f"{where}: expected a string")
    return value


def literal(value: Json, where: str) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str | int):
        return json.dumps(value, ensure_ascii=False)
    raise GenerationError(f"{where}: enum values must be strings, integers or booleans")


def union(members: list[str]) -> str:
    unique = list(dict.fromkeys(members))
    if "None" in unique:
        unique = [member for member in unique if member != "None"] + ["None"]
    return " | ".join(unique)


class Generator:
    def __init__(self, document: Json) -> None:
        self.document = as_schema(document, "document")
        version = self.document.get("openapi")
        if not isinstance(version, str) or not version.startswith("3.1"):
            raise GenerationError("Only OpenAPI 3.1 documents are supported")
        components = as_schema(self.document.get("components", {}), "components")
        self.schemas = as_schema(components.get("schemas", {}), "components.schemas")
        self.parameters = as_schema(components.get("parameters", {}), "components.parameters")
        self.definitions: dict[str, Definition] = {}

    def define(self, definition: Definition) -> str:
        if definition.name in self.definitions:
            raise GenerationError(f"Two definitions are named {definition.name}")
        if not definition.name.isidentifier() or keyword.iskeyword(definition.name):
            raise GenerationError(f"{definition.name} is not a valid Python name")
        self.definitions[definition.name] = definition
        return definition.name

    # Translation of schemas into type expressions.

    def check_keywords(self, schema: Schema, where: str) -> None:
        unknown = sorted(set(schema) - ANNOTATION_KEYWORDS - STRUCTURE_KEYWORDS)
        if unknown:
            raise GenerationError(f"{where}: unsupported keywords {', '.join(unknown)}")

    def reference(self, schema: Schema, where: str) -> str:
        target = as_str(schema["$ref"], where)
        prefix = "#/components/schemas/"
        name = target.removeprefix(prefix)
        if not target.startswith(prefix) or name not in self.schemas:
            raise GenerationError(f"{where}: unknown reference {target}")
        if len(set(schema) - ANNOTATION_KEYWORDS) > 1:
            raise GenerationError(f"{where}: $ref with sibling keywords")
        return name

    def types_of(self, schema: Schema, where: str) -> list[str]:
        declared = schema.get("type")
        if declared is None:
            return []
        if isinstance(declared, str):
            return [declared]
        return [as_str(item, where) for item in as_list(declared, where)]

    def render(
        self, schema: Schema, hint: str, where: str, *, top: bool = False
    ) -> tuple[str, set[str]]:
        """A type expression for `schema`; inline enums and objects become definitions `hint`."""
        self.check_keywords(schema, where)
        if "$ref" in schema:
            name = self.reference(schema, where)
            return name, {name}
        for combinator in ("allOf", "anyOf", "oneOf"):
            if combinator in schema:
                return self.render_combination(schema, combinator, hint, where)
        types = self.types_of(schema, where)
        nullable = "null" in types
        types = [kind for kind in types if kind != "null"]
        if "not" in schema and types != ["object"]:
            raise GenerationError(f"{where}: `not` is only supported on objects")
        if "const" in schema:
            expression = f"Literal[{literal(schema['const'], where)}]"
            return (f"{expression} | None" if nullable else expression), set()
        if "enum" in schema:
            return self.render_enum(schema, hint, where, nullable=nullable, top=top)
        if len(types) > 1:
            raise GenerationError(f"{where}: several non-null types")
        if nullable and not types:
            return "None", set()
        kind = types[0] if types else None
        expression, dependencies = self.render_kind(schema, kind, hint, where)
        return (f"{expression} | None" if nullable else expression), dependencies

    def render_kind(
        self, schema: Schema, kind: str | None, hint: str, where: str
    ) -> tuple[str, set[str]]:
        if kind == "string":
            return ("bytes" if schema.get("format") == "binary" else "str"), set()
        if kind in SCALARS:
            return SCALARS[kind], set()
        if kind == "array":
            items = as_schema(schema.get("items", {}), f"{where}.items")
            expression, dependencies = self.render(items, f"{hint}Item", f"{where}.items")
            return f"list[{expression}]", dependencies
        if kind == "object" or (kind is None and "properties" in schema):
            return self.render_object(schema, hint, where)
        if kind is None and not set(schema) - ANNOTATION_KEYWORDS:
            return "object", set()
        raise GenerationError(f"{where}: unsupported type {kind!r}")

    def render_enum(
        self, schema: Schema, hint: str, where: str, *, nullable: bool, top: bool
    ) -> tuple[str, set[str]]:
        values = as_list(schema["enum"], f"{where}.enum")
        nullable = nullable or None in values
        members = [literal(value, where) for value in values if value is not None]
        if not members:
            raise GenerationError(f"{where}: an enum with no values")
        expression = f"Literal[{', '.join(members)}]"
        if top:
            return (f"{expression} | None" if nullable else expression), set()
        name = self.define(Definition(name=hint, doc=describe(schema), expression=expression))
        return (f"{name} | None" if nullable else name), {name}

    def render_combination(
        self, schema: Schema, combinator: str, hint: str, where: str
    ) -> tuple[str, set[str]]:
        structure = set(schema) & STRUCTURE_KEYWORDS - {combinator, "discriminator"}
        if structure:
            raise GenerationError(f"{where}: {combinator} with {', '.join(sorted(structure))}")
        members = [as_schema(member, where) for member in as_list(schema[combinator], where)]
        if combinator == "allOf" and len(members) != 1:
            raise GenerationError(f"{where}: allOf is only supported with one member")
        expressions: list[str] = []
        dependencies: set[str] = set()
        for index, member in enumerate(members):
            expression, member_dependencies = self.render(
                member, hint, f"{where}.{combinator}[{index}]"
            )
            expressions.append(expression)
            dependencies |= member_dependencies
        if "discriminator" in schema:
            self.check_discriminator(schema, members, where)
        return union(expressions), dependencies

    def check_discriminator(self, schema: Schema, members: list[Schema], where: str) -> None:
        """A discriminated union narrows on its property: every mapping must match the members."""
        discriminator = as_schema(schema["discriminator"], f"{where}.discriminator")
        name = as_str(discriminator.get("propertyName"), f"{where}.discriminator.propertyName")
        mapping = as_schema(discriminator.get("mapping", {}), f"{where}.discriminator.mapping")
        referenced = {self.reference(member, where) for member in members if "$ref" in member}
        if len(referenced) != len(members):
            raise GenerationError(f"{where}: a discriminated union must list references only")
        for value, target in mapping.items():
            target_name = as_str(target, where).removeprefix("#/components/schemas/")
            if target_name not in referenced:
                raise GenerationError(f"{where}: mapping {value} points outside the union")
            member = self.schemas[target_name]
            properties = as_schema(
                as_schema(member, target_name).get("properties", {}), target_name
            )
            discriminant = as_schema(properties.get(name, {}), f"{target_name}.{name}")
            allowed = discriminant.get("enum", [discriminant.get("const")])
            if value not in as_list(allowed, f"{target_name}.{name}"):
                raise GenerationError(f"{where}: {target_name}.{name} does not allow {value}")

    def render_object(self, schema: Schema, hint: str, where: str) -> tuple[str, set[str]]:
        properties = schema.get("properties")
        extra = schema.get("additionalProperties")
        if properties is None:
            if isinstance(extra, dict):
                expression, dependencies = self.render(
                    extra, f"{hint}Value", f"{where}.additionalProperties"
                )
                return f"dict[str, {expression}]", dependencies
            return "dict[str, object]", set()
        name = self.define_typed_dict(hint, schema, where)
        return name, {name}

    # Definitions.

    def define_typed_dict(self, name: str, schema: Schema, where: str) -> str:
        unexpected = set(schema) & {"allOf", "anyOf", "oneOf", "enum", "const", "items"}
        if unexpected or self.types_of(schema, where) not in ([], ["object"]):
            raise GenerationError(f"{where}: properties mixed with other types")
        if "not" in schema:
            self.check_not(schema, where)
        extra = schema.get("additionalProperties")
        if extra not in (None, True, False):
            raise GenerationError(f"{where}: typed members with typed additionalProperties")
        properties = as_schema(schema.get("properties", {}), f"{where}.properties")
        required = {as_str(item, where) for item in as_list(schema.get("required", []), where)}
        missing = required - set(properties)
        if missing:
            raise GenerationError(f"{where}: required members without a schema: {sorted(missing)}")
        # Extra members (`additionalProperties: true`) cannot be typed: the description says so.
        definition = Definition(name=name, doc=describe(schema), fields=[])
        self.define(definition)
        fields: list[Field] = []
        for key, value in properties.items():
            if not key.isidentifier() or keyword.iskeyword(key):
                raise GenerationError(f"{where}: the member {key!r} is not a valid Python name")
            member = as_schema(value, f"{where}.{key}")
            expression, dependencies = self.render(
                member, f"{name}{upper_first(key)}", f"{where}.{key}"
            )
            definition.dependencies |= dependencies
            fields.append(Field(key, expression, key in required, describe(member)))
        definition.fields = fields
        return name

    def check_not(self, schema: Schema, where: str) -> None:
        """`not: {required: [...]}` forbids members: a TypedDict leaves them undeclared."""
        forbidden = as_schema(schema["not"], f"{where}.not")
        if set(forbidden) != {"required"}:
            raise GenerationError(f"{where}: `not` is only supported as not.required")
        properties = as_schema(schema.get("properties", {}), where)
        for key in as_list(forbidden["required"], f"{where}.not.required"):
            if as_str(key, where) in properties:
                raise GenerationError(f"{where}: {key} is both declared and forbidden")

    def define_component(self, name: str, schema: Schema) -> None:
        where = f"components.schemas.{name}"
        self.check_keywords(schema, where)
        if "properties" in schema:
            self.define_typed_dict(name, schema, where)
            return
        expression, dependencies = self.render(schema, name, where, top=True)
        self.define(
            Definition(
                name=name, doc=describe(schema), expression=expression, dependencies=dependencies
            )
        )

    def define_queries(self) -> None:
        """A TypedDict for the query of every operation that takes one, named after it."""
        paths = as_schema(self.document.get("paths", {}), "paths")
        for path, item in paths.items():
            for method, value in as_schema(item, path).items():
                if method not in ("get", "post", "put", "patch", "delete"):
                    continue
                operation = as_schema(value, f"{method} {path}")
                operation_id = as_str(operation.get("operationId"), f"{method} {path}")
                fields: list[Field] = []
                definition = Definition(
                    name=f"{upper_first(operation_id)}Query", doc="", fields=fields
                )
                for raw in as_list(operation.get("parameters", []), operation_id):
                    parameter = self.parameter(as_schema(raw, operation_id), operation_id)
                    if parameter.get("in") != "query":
                        continue
                    key = as_str(parameter.get("name"), operation_id)
                    where = f"{operation_id}.{key}"
                    if not key.isidentifier() or keyword.iskeyword(key):
                        raise GenerationError(f"{where}: not a valid Python name")
                    schema = as_schema(parameter.get("schema", {}), where)
                    expression, dependencies = self.render(
                        schema, f"{definition.name}{upper_first(key)}", where
                    )
                    definition.dependencies |= dependencies
                    doc = join_sentences(describe(parameter), describe(schema))
                    fields.append(Field(key, expression, parameter.get("required") is True, doc))
                if fields:
                    definition.doc = f"The query of `{operation_id}` ({method.upper()} {path})."
                    self.define(definition)

    def parameter(self, parameter: Schema, where: str) -> Schema:
        if "$ref" not in parameter:
            return parameter
        target = as_str(parameter["$ref"], where)
        name = target.removeprefix("#/components/parameters/")
        if not target.startswith("#/components/parameters/") or name not in self.parameters:
            raise GenerationError(f"{where}: unknown parameter {target}")
        return as_schema(self.parameters[name], target)

    # Output.

    def generate(self) -> str:
        for name in sorted(self.schemas):
            self.define_component(name, as_schema(self.schemas[name], name))
        self.define_queries()
        ordered = self.ordered()
        body = "\n\n\n".join(emit(definition) for definition in ordered)
        classes = [definition for definition in ordered if definition.fields is not None]
        aliases = [definition for definition in ordered if definition.fields is None]
        expressions = [item.annotation for item in fields_of(classes)]
        expressions += [definition.expression for definition in aliases]
        used = {
            "Literal": any("Literal[" in expression for expression in expressions),
            "NotRequired": any(not item.required for item in fields_of(classes)),
            "TypeAlias": bool(aliases),
            "TypedDict": bool(classes),
        }
        names = ", ".join(name for name, needed in used.items() if needed)
        # isort's spacing: two blank lines before a class, one before anything else.
        gap = "\n\n\n" if ordered and ordered[0].fields is not None else "\n\n"
        return f"{HEADER}\nfrom typing import {names}{gap}{body}\n"

    def ordered(self) -> list[Definition]:
        """Each definition after the ones it uses, otherwise by name: no forward references."""
        done: set[str] = set()
        visiting: set[str] = set()
        result: list[Definition] = []

        def visit(name: str) -> None:
            if name in done:
                return
            if name in visiting:
                raise GenerationError(
                    f"{name} refers to itself: forward references are not supported"
                )
            visiting.add(name)
            definition = self.definitions[name]
            for dependency in sorted(definition.dependencies):
                visit(dependency)
            visiting.discard(name)
            done.add(name)
            result.append(definition)

        for name in sorted(self.definitions):
            visit(name)
        return result


def describe(schema: Schema) -> str:
    """The docstring of a schema: its description, then its format and default."""
    parts: list[str] = []
    description = schema.get("description")
    if isinstance(description, str) and description.strip():
        parts.append(" ".join(description.split()))
    fmt = schema.get("format")
    if isinstance(fmt, str) and fmt not in ("binary", "password"):
        parts.append(f"Format: {fmt}.")
    if "default" in schema:
        parts.append(f"Default: `{json.dumps(schema['default'], ensure_ascii=False)}`.")
    return " ".join(parts)


def fields_of(definitions: list[Definition]) -> list[Field]:
    return [item for definition in definitions for item in definition.fields or []]


def join_sentences(first: str, second: str) -> str:
    return " ".join(part for part in (first, second) if part)


def docstring(text: str, indent: str) -> list[str]:
    """A triple-quoted string, wrapped to the line length, escaped where needed."""
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if escaped.endswith('"'):
        escaped = escaped[:-1] + '\\"'
    width = LINE_LENGTH - len(indent) - 6
    lines = textwrap.wrap(escaped, width=width, break_long_words=False, break_on_hyphens=False)
    if len(lines) <= 1:
        return [f'{indent}"""{escaped}"""']
    result = [f'{indent}"""{lines[0]}']
    result.extend(f"{indent}{line}" for line in lines[1:-1])
    result.append(f'{indent}{lines[-1]}"""')
    return result


def split_top_level(expression: str, separator: str) -> list[str]:
    """Splits on `separator` outside brackets."""
    parts: list[str] = []
    depth = 0
    current = ""
    index = 0
    while index < len(expression):
        char = expression[index]
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
        elif char == '"':
            end = expression.index('"', index + 1)
            current += expression[index : end + 1]
            index = end + 1
            continue
        if depth == 0 and expression.startswith(separator, index):
            parts.append(current)
            current = ""
            index += len(separator)
            continue
        current += char
        index += 1
    parts.append(current)
    return parts


def emit_assignment(prefix: str, expression: str) -> list[str]:
    """`prefix expression`, exploded one member per line (with a magic trailing comma) when long."""
    line = f"{prefix}{expression}"
    if len(line) <= LINE_LENGTH:
        return [line]
    if expression.startswith("Literal[") and expression.endswith("]") and " | " not in expression:
        members = split_top_level(expression[len("Literal[") : -1], ", ")
        return [f"{prefix}Literal[", *(f"{INDENT}{member}," for member in members), "]"]
    members = split_top_level(expression, " | ")
    return [
        f"{prefix}(",
        f"{INDENT}{members[0]}",
        *(f"{INDENT}| {member}" for member in members[1:]),
        ")",
    ]


def emit(definition: Definition) -> str:
    if definition.fields is None:
        lines = emit_assignment(f"{definition.name}: TypeAlias = ", definition.expression)
        if definition.doc:
            lines.extend(docstring(definition.doc, ""))
        return "\n".join(lines)
    lines = [f"class {definition.name}(TypedDict):"]
    if definition.doc:
        lines.extend(docstring(definition.doc, INDENT))
    for index, item in enumerate(definition.fields):
        if index > 0 or definition.doc:
            lines.append("")
        annotation = item.annotation if item.required else f"NotRequired[{item.annotation}]"
        line = f"{INDENT}{item.name}: {annotation}"
        if len(line) > LINE_LENGTH:
            raise GenerationError(
                f"{definition.name}.{item.name}: the annotation is too long for one line"
            )
        lines.append(line)
        if item.doc:
            lines.extend(docstring(item.doc, INDENT))
    if not definition.doc and not definition.fields:
        lines.append(f"{INDENT}pass")
    return "\n".join(lines)


def generate(contract: str) -> str:
    return Generator(cast("Json", json.loads(contract))).generate()


def download() -> tuple[str, str]:
    """Where the contract came from, and its text."""
    source_file = os.environ.get("FLASHPI_OPENAPI_FILE")
    if source_file:
        return source_file, Path(source_file).read_text(encoding="utf-8")
    url = os.environ.get("FLASHPI_OPENAPI_URL", DEFAULT_URL)
    if not url.startswith("https://"):
        raise SystemExit(f"Refusing to download the contract over a non-HTTPS URL: {url}")
    request = urllib.request.Request(url, headers={"accept": "application/json"})
    with urllib.request.urlopen(request, timeout=60) as response:
        body: bytes = response.read()
    return url, body.decode("utf-8")


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else "generate"
    if mode not in ("sync", "generate", "check") or len(argv) > 2:
        print("Usage: python scripts/openapi.py sync|generate|check", file=sys.stderr)
        return 2
    if mode == "sync":
        source, contract = download()
        parsed = json.loads(contract)  # fail early on a broken document
        if not isinstance(parsed, dict) or "openapi" not in parsed or "paths" not in parsed:
            raise SystemExit("The downloaded file is not an OpenAPI document")
        CONTRACT_PATH.write_text(
            contract if contract.endswith("\n") else f"{contract}\n", encoding="utf-8"
        )
        print(f"Copied {source} to openapi/openapi.json")
    types = generate(CONTRACT_PATH.read_text(encoding="utf-8"))
    relative = TYPES_PATH.relative_to(ROOT)
    if mode == "check":
        current = TYPES_PATH.read_text(encoding="utf-8") if TYPES_PATH.exists() else ""
        if current != types:
            print(
                f"{relative} is out of date. Run: uv run python scripts/openapi.py generate",
                file=sys.stderr,
            )
            return 1
        print(f"{relative} matches openapi/openapi.json")
        return 0
    TYPES_PATH.parent.mkdir(parents=True, exist_ok=True)
    TYPES_PATH.write_text(types, encoding="utf-8")
    print(f"Wrote {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
